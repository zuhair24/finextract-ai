import * as XLSX from 'xlsx';
import { CompanyReport } from '../types/finance';

export function exportReportToExcel(report: CompanyReport) {
  const wb = XLSX.utils.book_new();

  // 1. Executive Summary Sheet
  const summaryData: (string | number)[][] = [
    ['FINANCIAL EXTRACTION & RECONCILIATION REPORT'],
    ['Generated by FinExtract AI Engine'],
    [],
    ['Entity Name:', report.companyName],
    ['Ticker / Identifier:', report.ticker || 'N/A'],
    ['Sector / Industry:', report.sector],
    ['Reporting Fiscal Year:', report.fiscalYear],
    ['Comparative Fiscal Year:', report.previousFiscalYear],
    ['Currency & Scale:', `${report.reportingCurrency} (${report.reportingScale})`],
    ['Statement Type:', report.statementType],
    ['Source File:', report.sourceFileName || 'Uploaded PDF'],
    ['Extraction Model:', report.processingStats.modelUsed],
    ['Processed At:', report.processingStats.timestamp],
    [],
    ['CORE SUMMARY FINANCIAL METRICS', report.fiscalYear, report.previousFiscalYear, 'Unit'],
  ];

  // Pick top metrics
  const coreKeys = ['revenue', 'ebitda', 'pbt', 'pat', 'total_assets', 'total_liabilities', 'total_equity', 'total_debt', 'cash_and_equivalents', 'net_debt', 'operating_cash_flow'];
  coreKeys.forEach(k => {
    const m = report.metrics.find(metric => metric.key === k);
    if (m) {
      summaryData.push([
        m.label,
        m.currentYearValue !== null ? m.currentYearValue : 'N/A',
        m.previousYearValue !== null ? m.previousYearValue : 'N/A',
        m.unit,
      ]);
    }
  });

  const wsSummary = XLSX.utils.aoa_to_sheet(summaryData);
  XLSX.utils.book_append_sheet(wb, wsSummary, 'Summary');

  // 2. Financial Statements Sheet
  const statementsHeader = [
    'Category',
    'Standard Metric Label',
    'Reported Line Item Label',
    `Current Year (${report.fiscalYear})`,
    `Previous Year (${report.previousFiscalYear})`,
    'Unit',
    'Source Page #',
    'Statement Section',
    'Verbatim Document Excerpt',
    'Confidence Score (%)',
    'Auditor Notes',
  ];

  const statementsRows = report.metrics.map(m => [
    m.category,
    m.label,
    m.reportedLabel,
    m.currentYearValue ?? '',
    m.previousYearValue ?? '',
    m.unit,
    m.sourcePage,
    m.sourceSection,
    m.verbatimSnippet,
    `${m.confidence}%`,
    m.notes || '',
  ]);

  const wsStatements = XLSX.utils.aoa_to_sheet([statementsHeader, ...statementsRows]);
  XLSX.utils.book_append_sheet(wb, wsStatements, 'Financial Statements');

  // 3. Reconciliation & Sanity Checks Sheet
  const reconciliationData = [
    ['RECONCILIATION & SANITY CHECKS AUDIT TRAIL'],
    ['Formula / Assertion', 'Status', 'Discrepancy', 'Calculated vs Reported', 'Auditor Explanation'],
    [
      report.reconciliationChecks.balanceSheetIdentity.formula,
      report.reconciliationChecks.balanceSheetIdentity.passed ? 'PASSED' : 'FLAGGED',
      report.reconciliationChecks.balanceSheetIdentity.discrepancy,
      `Assets: ${report.reconciliationChecks.balanceSheetIdentity.totalAssets} vs Sum: ${report.reconciliationChecks.balanceSheetIdentity.calculatedSum}`,
      report.reconciliationChecks.balanceSheetIdentity.explanation,
    ],
    [
      report.reconciliationChecks.netDebtIdentity.formula,
      report.reconciliationChecks.netDebtIdentity.passed ? 'PASSED' : 'FLAGGED',
      report.reconciliationChecks.netDebtIdentity.discrepancy,
      `Calculated: ${report.reconciliationChecks.netDebtIdentity.calculatedNetDebt} vs Reported: ${report.reconciliationChecks.netDebtIdentity.reportedNetDebt}`,
      report.reconciliationChecks.netDebtIdentity.explanation,
    ],
    [
      'EBITDA & PAT Margin Sanity Check',
      report.reconciliationChecks.profitabilityMargins.passed ? 'PASSED' : 'FLAGGED',
      0,
      `EBITDA Margin: ${report.reconciliationChecks.profitabilityMargins.ebitdaMarginPct}% | PAT Margin: ${report.reconciliationChecks.profitabilityMargins.patMarginPct}%`,
      report.reconciliationChecks.profitabilityMargins.explanation,
    ],
  ];

  const wsRecon = XLSX.utils.aoa_to_sheet(reconciliationData);
  XLSX.utils.book_append_sheet(wb, wsRecon, 'Reconciliation Checks');

  // 4. Page Citations Sheet
  const citationHeader = ['Metric', 'Source Page', 'Section Name', 'Verbatim Excerpt from Annual Report', 'Confidence'];
  const citationRows = report.metrics.map(m => [
    m.label,
    `Page ${m.sourcePage}`,
    m.sourceSection,
    m.verbatimSnippet,
    `${m.confidence}%`,
  ]);
  const wsCitations = XLSX.utils.aoa_to_sheet([citationHeader, ...citationRows]);
  XLSX.utils.book_append_sheet(wb, wsCitations, 'Page Citations Log');

  // Write and download
  const cleanName = report.companyName.replace(/[^a-zA-Z0-9]/g, '_');
  const filename = `${cleanName}_${report.fiscalYear}_Extracted_Financials.xlsx`;
  XLSX.writeFile(wb, filename);
}

export function exportComparablesToExcel(reports: CompanyReport[]) {
  const wb = XLSX.utils.book_new();

  const metricsToCompare = [
    { key: 'revenue', label: 'Revenue from Operations (₹ Cr)' },
    { key: 'ebitda', label: 'Operating Profit EBITDA (₹ Cr)' },
    { key: 'pat', label: 'Net Profit / PAT (₹ Cr)' },
    { key: 'total_assets', label: 'Total Assets (₹ Cr)' },
    { key: 'total_debt', label: 'Total Debt / Borrowings (₹ Cr)' },
    { key: 'net_debt', label: 'Net Debt (₹ Cr)' },
    { key: 'operating_cash_flow', label: 'Operating Cash Flow (₹ Cr)' },
  ];

  const header = ['Financial Metric', ...reports.map(r => `${r.companyName} (${r.fiscalYear})`)];
  const rows = metricsToCompare.map(m => {
    return [
      m.label,
      ...reports.map(r => {
        const found = r.metrics.find(metric => metric.key === m.key);
        return found?.currentYearValue ?? 'N/A';
      }),
    ];
  });

  const ws = XLSX.utils.aoa_to_sheet([
    ['10-COMPANY COMPARABLES MATRIX - ANNUAL REPORT EXTRACTION'],
    [],
    header,
    ...rows,
  ]);

  XLSX.utils.book_append_sheet(wb, ws, 'Comparables Matrix');
  XLSX.writeFile(wb, 'Indian_Companies_Annual_Report_Comparables.xlsx');
}
